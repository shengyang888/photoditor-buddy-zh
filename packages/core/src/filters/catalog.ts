/** Finds a filter by id. Returns undefined for unknown ids instead of throwing. */
export function findFilter(id: string): FilterDefinition | undefined {
  return FILTER_CATALOG.find((filter) => filter.id === id);
}

/** All filters of one category, in catalogue order. */
export function filtersInCategory(category: FilterCategory): FilterDefinition[] {
  return FILTER_CATALOG.filter((filter) => filter.category === category);
}
