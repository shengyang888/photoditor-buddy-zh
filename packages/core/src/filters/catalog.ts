import type { AdjustmentPreset } from '../adjustments/merge';
import type { FilterCategory, FilterDefinition, LutRecipe } from './types';

/**
 * Compact constructor used by the tables below. Ids are derived from the stable English
 * `idKey` (e.g. 'Film-Portra 400') so they stay stable across renames and translations
 * (they are stored in saved projects and in the SDK API). `name` is the display name
 * shown in the UI. When a call has a LUT recipe, pass it as the 4th argument and the
 * idKey as the 5th; without a LUT, the idKey goes in the 4th argument.
 */
function f(
  category: FilterCategory,
  name: string,
  preset: AdjustmentPreset,
  lutOrId?: LutRecipe | string,
  idKey?: string,
): FilterDefinition {
  const lut = typeof lutOrId === 'string' ? undefined : lutOrId;
  const key = typeof lutOrId === 'string' ? lutOrId : (idKey ?? `${category}-${name}`);
  const id = key
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
  return lut ? { id, name, category, preset, lut } : { id, name, category, preset };
}

/** Shortcut for a split-toning block (highlight hue/sat, shadow hue/sat, balance). */
function tone(
  hh: number,
  hs: number,
  sh: number,
  ss: number,
  balance = 0,
): AdjustmentPreset['splitToning'] {
  return {
    highlightHue: hh,
    highlightSaturation: hs,
    shadowHue: sh,
    shadowSaturation: ss,
    balance,
  };
}

