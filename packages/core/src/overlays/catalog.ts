/** Returns a CSS font-family string with fallbacks for the given family. */
export function fontStack(family: string): string {
  const option = FONT_OPTIONS.find((f) => f.family === family);
  return option ? `"${option.family}", ${option.fallback}` : `"${family}", system-ui, sans-serif`;
}

